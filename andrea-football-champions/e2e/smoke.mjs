import { createRequire } from 'module';
const { chromium, devices } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ ...devices['iPhone 13 landscape'] });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:4173/');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'e2e/shots/01-splash.png' });
await page.tap('[data-testid=splash]');
await page.waitForTimeout(2500);
await page.screenshot({ path: 'e2e/shots/02-welcome.png' });
await page.tap('[data-testid=btn-giochiamo]');
await page.waitForTimeout(500);
await page.tap('[data-testid=team-roma]');
await page.tap('[data-testid=team-ok]');
await page.waitForTimeout(800);
await page.screenshot({ path: 'e2e/shots/03-menu.png' });
await page.tap('[data-testid=menu-play]');
await page.waitForTimeout(2500);
await page.screenshot({ path: 'e2e/shots/04-level1.png' });
console.log('errors', errors);
await browser.close();
